ABSTRACT = (
 "Background. Optical vibrational spectroscopy — principally Raman, with near-infrared (NIR) "
 "reflectance as a lower-cost proxy — combined with machine learning has been proposed as a "
 "non-invasive skin-cancer triage adjunct, yet the field remains dominated by small single-centre "
 "cohorts and by deep networks reported without a matched classical baseline or leakage-free "
 "validation. Objective. To determine whether architecture or methodology governs clinical "
 "readiness in this data regime. Methods. We synthesise twelve attributable optical skin-cancer "
 "studies and benchmark seven models (four classical, three deep) under identical, fold-isolated "
 "preprocessing and patient-level grouped cross-validation on two public NIR cohorts, NIR-SC-UFES "
 "(647 spectra, 319 patients) and Deteccthia (152 lesion-level spectra), with discrimination, "
 "calibration, repeated and nested cross-validation, decision-curve analysis and a three-class "
 "extension. Results. Logistic regression reaches an "
 "area under the receiver-operating-characteristic curve (AUC) of 0.774 (95% CI 0.709–0.838) "
 "versus 0.663 (0.596–0.727) for the best deep model (1D-CNN); classical models win in 20/20 "
 "seeds (Friedman p=6.2×10⁻²²) with lower seed-to-seed variance "
 "(Levene p=0.0018). Deep models are significantly worse calibrated (Holm-adjusted p≤0.024) and "
 "overfit within a median of 8–21 epochs. Platt scaling halves the expected calibration error "
 "(0.077→0.038). No model transported to the external cohort (all AUC ≤0.56; class-signature "
 "correlation r=−0.17). The ordering persists in the three-class task (macro AUC 0.829 versus "
 "0.741). Conclusions. In this small-cohort regime, classical chemometric models match or exceed "
 "deep networks and calibrate more readily, and no single-instrument model survives external "
 "validation. Gains will come from larger multi-centre cohorts, patient-level leakage-free "
 "validation and probability calibration, not from deeper architectures."
)

