P57 = ("The development cohort, NIR-SC-UFES [{loss2024}], comprises portable MicroNIR spectra (125 "
 "channels, 908–1676 nm) acquired in vivo: 714 spectra from 331 patients, with a median of 2 "
 "replicate spectra per patient (maximum 16). Following the public labelling we form a binary task "
 "of malignant/pre-malignant {ACK, BCC, SCC, MEL} (499 spectra) versus benign {NEV, SEK} (148 "
 "spectra), n=647 spectra from 319 patients after excluding ambiguous “other” lesions (Table 2). "
 "Because replicate spectra from one patient are highly correlated, every split in this work is "
 "grouped at the patient level (stratified grouped cross-validation): no patient contributes "
 "spectra to both training and test partitions. This is stricter than the lesion-level splitting "
 "our checklist (Section 10) demands of the literature, and we quantify below the optimism that "
 "spectrum-level splitting would have introduced (0.03–0.07 AUC; Section 12). The external cohort, "
 "Deteccthia [{courtenay2024}], provides pushbroom NIR hyperspectral imaging (150 bands, "
 "900–1606 nm) reduced to 152 lesion-level mean spectra (115 malignant {BCC, SCC, AK} versus 37 "
 "healthy skin), aggregated per acquisition to avoid pseudo-replication. For cross-instrument "
 "application, Deteccthia spectra are linearly interpolated onto the NIR-SC-UFES wavelength grid "
 "over the common 908–1602 nm range (113 channels). Preprocessing is identical for all models and "
 "fully fold-isolated: L2 row-normalisation, SNV (Eq. (1)), then per-channel standardisation "
 "fitted on the training fold only. All splits are 5-fold stratified grouped with fixed seed 42; "
 "deep models use the same folds.")

